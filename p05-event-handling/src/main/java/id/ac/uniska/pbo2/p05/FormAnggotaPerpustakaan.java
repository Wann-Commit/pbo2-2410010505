    private void batalButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_batalButtonActionPerformed
        // TODO add your handling code here:
        npmField.setText("");
        perbaruiHitungNpmLabel();
        namaField.setText("");
        prodiCombo.setSelectedIndex(0);
        jenisGroup.clearSelection();
        emailField.setText("");
        nomorField.setText("");
        alamatArea.setText("");
        setujuCheck.setSelected(false);
        npmField.requestFocusInWindow();
    }//GEN-LAST:event_batalButtonActionPerformed

    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        // TODO add your handling code here:
        // BLOK 1: ambil data dari komponen, simpan ke variabel
        String npm = npmField.getText().trim();
        String nama = namaField.getText().trim();          
        String prodi = (String) prodiCombo.getSelectedItem();
        String email = emailField.getText().trim();
        String nomorHp = nomorField.getText().trim();
        String alamat = alamatArea.getText().trim();        
        String jenis = "";
        
        if (mahasiswaRadio.isSelected()) {
            jenis = "Mahasiswa";
        } else if (dosenRadio.isSelected()) {
            jenis = "Dosen";
        } else if (umumRadio.isSelected()) {
            jenis = "Umum";
        } else {
            jenis = "Belum dipilih";
        }

        // BLOK 2: susun satu String ringkasan
        String ringkasan = "NPM: " + npm + "\n"
                + "Nama: " + nama + "\n"
                + "Program Studi: " + prodi + "\n"
                + "Jenis Anggota: " + jenis + "\n"
                + "Email: " + email + "\n"
                + "Nomor HP: " + nomorHp + "\n"
                + "Alamat: " + alamat;

        // BLOK 3: tampilkan
        JOptionPane.showMessageDialog(this, ringkasan);
    }//GEN-LAST:event_daftarButtonActionPerformed

